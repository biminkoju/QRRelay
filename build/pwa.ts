import { writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

function collectFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...collectFiles(full));
    else out.push(full);
  }
  return out;
}

/** Emits a cache-first service worker precaching the exact PWA asset list. */
export function pwaPlugin(buildId: string, outDir = 'dist'): Plugin {
  return {
    name: 'qrrelay-pwa',
    apply: 'build',
    closeBundle() {
      const root = join(process.cwd(), outDir);
      const assets = collectFiles(root)
        .map((f) => './' + relative(root, f).split('\\').join('/'))
        .filter((p) => p !== './sw.js');
      const cache = 'qrrelay-' + buildId;
      const sw = [
        '/* generated by build/pwa.ts */',
        'const CACHE = ' + JSON.stringify(cache) + ';',
        'const ASSETS = ' + JSON.stringify(assets) + ';',
        "self.addEventListener('install', (event) => {",
        '  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));',
        '});',
        "self.addEventListener('activate', (event) => {",
        '  event.waitUntil(',
        '    caches',
        '      .keys()',
        '      .then((keys) =>',
        '        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))',
        '      )',
        '      .then(() => self.clients.claim())',
        '  );',
        '});',
        "self.addEventListener('fetch', (event) => {",
        "  if (event.request.method !== 'GET') return;",
        '  event.respondWith(',
        '    caches.match(event.request).then((cached) =>',
        "      cached || caches.match('./index.html')",
        '    )',
        '  );',
        '});',
        '',
      ].join('\n');
      writeFileSync(join(root, 'sw.js'), sw);
    },
  };
}
